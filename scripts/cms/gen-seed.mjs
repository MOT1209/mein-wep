#!/usr/bin/env node
/**
 * Writes supabase/seed/20261103120100_seed_cms.sql from the content that is in
 * git today, so the database starts with exactly what the site shows now:
 *
 *   _data/studioCatalog.json  -> project_categories + studio_projects
 *   _data/site.json (siteNav) -> navigation_items
 *   (site name setting)       -> website_settings
 *
 * Idempotent: every insert is ON CONFLICT DO NOTHING, so running the seed on a
 * database that already has rows changes nothing the owner has edited.
 *
 *   node scripts/cms/gen-seed.mjs
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const read = (p) => JSON.parse(fs.readFileSync(path.join(ROOT, p), 'utf8'));

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `array[${(a ?? []).map(q).join(', ')}]::text[]`;
const json = (o) => `${q(JSON.stringify(o ?? {}))}::jsonb`;
const slugify = (s) => s.toLowerCase().replace(/&/g, 'and').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

// The standard categories the owner asked for, plus every category the
// current catalogue already uses (so no public label changes on migration).
const STANDARD = [
  ['ai-projects', 'AI Projects', 'KI-Projekte', 'مشاريع الذكاء الاصطناعي'],
  ['ai-agents', 'AI Agents', 'KI-Agenten', 'وكلاء الذكاء الاصطناعي'],
  ['developer-tools', 'Developer Tools', 'Entwicklerwerkzeuge', 'أدوات المطورين'],
  ['browsers', 'Browsers', 'Browser', 'المتصفحات'],
  ['ides', 'IDEs', 'IDEs', 'بيئات التطوير'],
  ['games', 'Games', 'Spiele', 'الألعاب'],
  ['applications', 'Applications', 'Anwendungen', 'التطبيقات'],
  ['websites', 'Websites', 'Websites', 'المواقع'],
  ['automation', 'Automation', 'Automatisierung', 'الأتمتة'],
  ['experimental', 'Experimental Projects', 'Experimentelle Projekte', 'مشاريع تجريبية'],
];

const catalog = read('_data/studioCatalog.json').projects;
const site = read('_data/site.json');
const i18n = Object.fromEntries(['en', 'de', 'ar'].map((l) => [l, read(`_data/i18n/${l}.json`)]));

const categories = new Map(STANDARD.map(([slug, en, de, ar], i) => [slug, { slug, en, de, ar, order: (i + 1) * 10 }]));
for (const p of catalog) {
  if (!p.category) continue;
  const slug = slugify(p.category);
  if (!categories.has(slug)) {
    categories.set(slug, {
      slug, en: p.category, de: p.i18n?.de?.category ?? null, ar: p.i18n?.ar?.category ?? null,
      order: 200 + categories.size,
    });
  }
}

const out = [];
out.push('-- Generated by scripts/cms/gen-seed.mjs from the content in git. Do not edit by hand.');
out.push('-- Safe to re-run: existing rows are left as they are.');
out.push('begin;');
out.push('');
out.push('insert into public.project_categories (slug, name, name_de, name_ar, sort_order) values');
out.push([...categories.values()].map((c) => `  (${q(c.slug)}, ${q(c.en)}, ${q(c.de)}, ${q(c.ar)}, ${c.order})`).join(',\n'));
out.push('on conflict (slug) do nothing;');
out.push('');

catalog.forEach((p, i) => {
  const i18nOut = {};
  for (const l of ['de', 'ar']) {
    const t = p.i18n?.[l];
    if (!t) continue;
    const { category, ...rest } = t; // category text now lives on the category
    if (Object.keys(rest).length) i18nOut[l] = rest;
  }
  out.push(`insert into public.studio_projects (slug, section, title, short_description, project_type, category_id,
  platforms, technologies, features, status, featured, visibility, sort_order, cover_image, image_alt,
  launch_url, apk_id, i18n)
select ${q(p.id)}, ${q(p.section)}, ${q(p.title)}, ${q(p.description)}, ${q(p.type)},
  (select id from public.project_categories where slug = ${q(p.category ? slugify(p.category) : null)}),
  ${arr(p.platforms)}, ${arr(p.technologies)}, ${arr(p.features)}, ${q(p.status)}, ${p.featured ? 'true' : 'false'},
  ${q(p.hidden ? 'hidden' : 'public')}, ${(i + 1) * 10}, ${q(p.image ?? null)}, ${q(p.imageAlt ?? null)},
  ${q(p.launchUrl ?? null)}, ${q(p.apkId ?? null)}, ${json(i18nOut)}
on conflict (slug) do nothing;`);
});
out.push('');

out.push('insert into public.navigation_items (nav_key, label, label_de, label_ar, href, sort_order, visible) values');
out.push(site.siteNav.map((n, i) => `  (${q(n.key)}, ${q(i18n.en.nav?.[n.key] ?? n.label)}, ${q(i18n.de.nav?.[n.key] ?? null)}, ${q(i18n.ar.nav?.[n.key] ?? null)}, ${q(n.href)}, ${(i + 1) * 10}, true)`).join(',\n'));
out.push('on conflict (nav_key) do nothing;');
out.push('');

out.push('insert into public.website_settings (key, value, is_public) values');
out.push([
  `  ('site.name', ${json({ value: 'Rashid Ali' })}, true)`,
  `  ('studio.featured_first', ${json({ value: true })}, true)`,
].join(',\n'));
out.push('on conflict (key) do nothing;');
out.push('');
out.push('commit;');

const target = path.join(ROOT, 'supabase/seed/20261103120100_seed_cms.sql');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, `${out.join('\n')}\n`);
console.log(`wrote ${path.relative(ROOT, target)}: ${categories.size} categories, ${catalog.length} projects, ${site.siteNav.length} nav items`);
